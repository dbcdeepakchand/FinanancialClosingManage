CREATE TABLE FIN_CLOSE_TASKS (
  ID           VARCHAR2(100 CHAR)  NOT NULL,
  TITLE        VARCHAR2(300 CHAR)  NOT NULL,
  MODULE_NAME  VARCHAR2(100 CHAR)  NOT NULL,
  FREQUENCY    VARCHAR2(20 CHAR)   NOT NULL,
  OWNER_NAME   VARCHAR2(150 CHAR)  NOT NULL,
  DUE_DAY      NUMBER(2)           NOT NULL,
  PRIORITY     VARCHAR2(20 CHAR)   NOT NULL,
  STATUS       VARCHAR2(30 CHAR)   NOT NULL,
  ENTITY_ID    VARCHAR2(50 CHAR)   NOT NULL,
  NOTE         VARCHAR2(4000 CHAR),
  TEMPLATE_ID  NUMBER,
  CREATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_FIN_CLOSE_TASKS PRIMARY KEY (ID),
  CONSTRAINT CK_FCT_DUE_DAY CHECK (DUE_DAY BETWEEN 1 AND 31),
  CONSTRAINT CK_FCT_FREQUENCY CHECK (FREQUENCY IN ('Both', 'Monthly', 'Quarterly')),
  CONSTRAINT CK_FCT_PRIORITY CHECK (PRIORITY IN ('Low', 'Medium', 'High')),
  CONSTRAINT CK_FCT_STATUS CHECK (STATUS IN ('Not started', 'In progress', 'Blocked', 'Complete'))
);
