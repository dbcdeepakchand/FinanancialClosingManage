-- Backfill checklist ledger IDs from the business-unit ledger mapping.
-- Only NULL IDs with exactly one matching distinct ledger ID are updated.
-- Review the before/after queries, then COMMIT or ROLLBACK manually.

SELECT checklist.CHECKLIST_ROW_ID,
       checklist.LEDGER_NAME,
       COUNT(DISTINCT mapping.LEDGER_ID) AS MATCHING_LEDGER_IDS
  FROM XX_OPERATIONAL_CHECKLIST checklist
  LEFT JOIN XX_BU_LE_LEDGER_MAPPING mapping
    ON UPPER(TRIM(mapping.LEDGER_NAME)) = UPPER(TRIM(checklist.LEDGER_NAME))
 WHERE checklist.LEDGER_ID IS NULL
 GROUP BY checklist.CHECKLIST_ROW_ID, checklist.LEDGER_NAME
HAVING COUNT(DISTINCT mapping.LEDGER_ID) <> 1
 ORDER BY checklist.CHECKLIST_ROW_ID;

MERGE INTO XX_OPERATIONAL_CHECKLIST checklist
USING (
  SELECT UPPER(TRIM(LEDGER_NAME)) AS NORMALIZED_LEDGER_NAME,
         MIN(LEDGER_ID) AS LEDGER_ID
    FROM XX_BU_LE_LEDGER_MAPPING
   WHERE LEDGER_NAME IS NOT NULL
     AND LEDGER_ID IS NOT NULL
   GROUP BY UPPER(TRIM(LEDGER_NAME))
  HAVING COUNT(DISTINCT LEDGER_ID) = 1
) mapping
ON (
  checklist.LEDGER_ID IS NULL
  AND UPPER(TRIM(checklist.LEDGER_NAME)) = mapping.NORMALIZED_LEDGER_NAME
)
WHEN MATCHED THEN
  UPDATE SET checklist.LEDGER_ID = mapping.LEDGER_ID;

SELECT CHECKLIST_ROW_ID, LEDGER_NAME, LEDGER_ID
  FROM XX_OPERATIONAL_CHECKLIST
 WHERE LEDGER_ID IS NULL
 ORDER BY CHECKLIST_ROW_ID;
