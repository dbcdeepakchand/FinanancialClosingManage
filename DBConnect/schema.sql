CREATE TABLE XX_OPERATIONAL_CHECKLIST (
  CHECKLIST_ROW_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  MODULE_NAME            VARCHAR2(50 BYTE),
  LEDGER_ID              NUMBER,
  LEDGER_NAME            VARCHAR2(255 BYTE),
  PROCESS_OWNER          VARCHAR2(100 BYTE),
  PROCESS_NAME           VARCHAR2(4000 BYTE),
  PROCESS_DESCRIPTION    VARCHAR2(4000 BYTE),
  ACTION_BY              VARCHAR2(100 BYTE),
  PRE_REQUISITE_DESC     VARCHAR2(4000 BYTE),
  ACTION_TYPE            VARCHAR2(255 BYTE),
  PROCESS_TYPE           VARCHAR2(255 BYTE),
  CREATED_BY             NUMBER,
  CREATION_DATE          DATE,
  LAST_UPDATED_BY        NUMBER,
  LAST_UPDATE_DATE       DATE,
  LAST_UPDATE_LOGIN      NUMBER,
  CONSTRAINT PK_OPERATIONAL_CHECKLIST PRIMARY KEY (CHECKLIST_ROW_ID)
);

COMMENT ON TABLE XX_OPERATIONAL_CHECKLIST IS
  'Financial closing sequence operational checklist organized by ledger.';

CREATE INDEX IDX_CHKLIST_MODULE ON XX_OPERATIONAL_CHECKLIST (MODULE_NAME);
CREATE INDEX IDX_CHKLIST_OWNER ON XX_OPERATIONAL_CHECKLIST (PROCESS_OWNER);
CREATE INDEX IDX_CHKLIST_LEDGER ON XX_OPERATIONAL_CHECKLIST (LEDGER_ID);

CREATE TABLE XX_OPERATIONAL_CHECKLIST_PROGRESS (
  CHECKLIST_ROW_ID VARCHAR2(100 CHAR) NOT NULL,
  LEDGER_ID        NUMBER NOT NULL,
  STATUS           VARCHAR2(30 CHAR) DEFAULT 'Not started' NOT NULL,
  OWNER_NAME       VARCHAR2(150 CHAR) NOT NULL,
  PERIOD           VARCHAR2(100 CHAR) NOT NULL,
  NOTE             VARCHAR2(4000 CHAR),
  NOTE_OVERRIDDEN  CHAR(1) DEFAULT 'N' NOT NULL,
  CREATED_AT       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_XX_OC_PROGRESS
    PRIMARY KEY (CHECKLIST_ROW_ID, LEDGER_ID, PERIOD),
  CONSTRAINT CK_XX_OC_PROGRESS_STATUS
    CHECK (STATUS IN ('Not started', 'In progress', 'Blocked', 'Complete')),
  CONSTRAINT CK_XX_OC_PROGRESS_NOTE
    CHECK (NOTE_OVERRIDDEN IN ('Y', 'N'))
);

CREATE INDEX IDX_XX_OC_PROGRESS_PERIOD
  ON XX_OPERATIONAL_CHECKLIST_PROGRESS (LEDGER_ID, PERIOD);
